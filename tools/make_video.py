"""Assembles deliverables/CCGN_Demo.mp4: narrated intro slides -> recorded live walkthrough -> results.

Inputs (all generated by the other tools):
  deliverables/slides/slide-NN.png           tools/render_slides.ps1
  deliverables/walkthrough/frames.txt|steps.json   tools/record_walkthrough.mjs
  deliverables/narration/<key>.wav + durations.json  tools/make_narration.ps1
Usage: python tools/make_video.py        (ffmpeg and ffprobe on PATH)
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "deliverables"
PAD = 0.9                      # seconds of picture after each narrated slide
INTRO = [("slide_title", 1), ("slide_problem", 2), ("slide_onem2m", 5), ("slide_mec", 6), ("slide_flow", 4),
         ("slide_dashboard", 11)]
OUTRO = [("slide_latency", 13), ("slide_ai", 14), ("slide_etsi", 15), ("slide_close", 18)]


def main():
    dur = json.loads((D / "narration" / "durations.json").read_text(encoding="utf-8-sig"))
    walk = json.loads((D / "walkthrough" / "steps.json").read_text(encoding="utf-8"))
    inputs, vlabels, filters, clips = [], [], [], []      # clips: (wav, start seconds)
    t = 0.0

    def still(key, number):
        nonlocal t
        length = dur[key] + PAD
        inputs.extend(["-loop", "1", "-t", f"{length:.2f}", "-i", str(D / "slides" / f"slide-{number:02d}.png")])
        clips.append((D / "narration" / f"{key}.wav", t + 0.3))
        t += length

    for key, number in INTRO:
        still(key, number)
    inputs.extend(["-f", "concat", "-safe", "0", "-i", str(D / "walkthrough" / "frames.txt")])
    for step in walk["steps"]:
        clips.append((D / "narration" / f"{step['key']}.wav", t + step["t"] / 1000 + 0.2))
    t += walk["total_ms"] / 1000
    for key, number in OUTRO:
        still(key, number)

    video_count = len(INTRO) + 1 + len(OUTRO)
    for i in range(video_count):
        filters.append(f"[{i}:v]scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2:color=white,"
                       f"fps=30,format=yuv420p,setsar=1[v{i}]")
        vlabels.append(f"[v{i}]")
    filters.append("".join(vlabels) + f"concat=n={video_count}:v=1:a=0[vout]")
    alabels = []
    for j, (wav, start) in enumerate(clips):
        inputs.extend(["-i", str(wav)])
        ms = int(start * 1000)
        filters.append(f"[{video_count + j}:a]aresample=48000,adelay={ms}|{ms}[a{j}]")
        alabels.append(f"[a{j}]")
    filters.append("".join(alabels) + f"amix=inputs={len(clips)}:normalize=0:dropout_transition=0,"
                   f"apad,atrim=0:{t:.2f},volume=1.6[aout]")
    out = D / "CCGN_Demo.mp4"
    subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *inputs,
                    "-filter_complex", ";".join(filters), "-map", "[vout]", "-map", "[aout]",
                    "-c:v", "libx264", "-preset", "medium", "-crf", "20", "-c:a", "aac", "-b:a", "160k",
                    "-movflags", "+faststart", str(out)], check=True)
    probe = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration,size", "-of", "json", str(out)],
                           capture_output=True, text=True, check=True)
    info = json.loads(probe.stdout)["format"]
    print(f"Saved {out}: {float(info['duration']):.1f} s, {int(info['size']) / 1e6:.1f} MB, {len(clips)} narration clips")


if __name__ == "__main__":
    main()
